# +  dodawanie
# *  mnożenie
# **  potęgowanie
# /  dzielenie
# //  dzielenie całkowite
# %  reszta z dzielenia
# >  większe
# >=  większe lub równe
# <  mniejsze
# <=  mniejsze lub równe
print(3 * 2 + 1) # trzy argumanry, dwa operatory
print(5 + 10 * 5) # trzy argumenty, dwa operatory
print(4 + 4 / 2 ** 2) # cztery argumenty, trzy operatory
print(4 % 3 % 2 % 1) # cztery argumenty, trzy operatory
print(1 + 2 % 3 ** 4 * 5) # pięć argumentów, cztery operatory
print(True != False) # dwa argumenty, jeden operator
print(type(50)) 
print(type(149.17)) 
print(type(4 * 7))
print(type(4.0 * 7))
print(type("Krakow University of Economics"))
print(type(True))
print(type(2 > 5))