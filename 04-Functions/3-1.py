# To use the functions available in an external module,
# you must include that module in your program.
import math

square_root = math.sqrt(7)
print('A square root of 7 is', square_root)

logarithm = math.log(5)
print('The natural logarithm of 5 is', logarithm)

radian_degrees = math.radians(90)
print('90 degrees is equivalent to', radian_degrees, 'radians')

sinus = math.sin(math.radians(90))
print('The sine of 90 degrees is', sinus)
